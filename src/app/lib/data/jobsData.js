// Helper function to get job by slug
export function getJobBySlug(slug) {
  return jobsData.find(job => job.slug === slug);
}

// Helper function to get all job slugs (for static generation)
export function getAllJobSlugs() {
  return jobsData.map(job => job.slug);
}

// Helper function to get basic job info for listing page
export function getJobsListData() {
  return jobsData.map(job => ({
    slug: job.slug,
    title: job.title,
    location: job.location,
    experience: job.experience,
    jobType: job.jobType,
    category: job.category
  }));
}

// Helper function to get unique categories
export function getJobCategories() {
  const categories = [...new Set(jobsData.map(job => job.category))];
  return categories.sort();
}
